import matplotlib.pyplot as plt
import numpy as np

# --- Confusion matrices ---
M1 = np.array([
    [0, 0, 13],
    [0, 1, 1],
    [2, 22, 0]
])

M2 = np.array([
    [0, 1, 2],
    [6, 3, 1],
    [7, 19, 0]
])

M3 = np.array([
    [0, 0, 11],
    [1, 6, 0],
    [27, 0, 0]
])

M4 = np.array([
    [3, 0, 33],
    [0, 0, 1],
    [32, 1, 2]
])

matrices = [M1, M2, M3, M4]
titles = [
    "Adjustment of Interest on Arrears — Proposition One\n(Overall Accuracy = 0.410)",
    "Adjustment of Interest on Arrears — Proposition Two\n(Overall Accuracy = 0.308)",
    "Imprescriptibility of Murder\n(Overall Accuracy = 0.978)",
    "Lowering Import Tax Exemption\n(Overall Accuracy = 0.903)"
]

x_labels = ["Negative", "Neutral", "Positive"]
y_labels = ["Positive", "Neutral", "Negative"]

fig, axes = plt.subplots(2, 2, figsize=(13, 12))
fig.suptitle(
    "Confusion Matrices for Sentiment Classification\n across Policy Cases (GPT-5-mini)",
    fontsize=20,
    y=0.98
)

# lighter visual saturation
vmax = 40
cmap = "OrRd"

for ax, M, title in zip(axes.flatten(), matrices, titles):
    im = ax.imshow(M, cmap=cmap, vmin=0, vmax=vmax)

    # numbers in each cell
    for i in range(M.shape[0]):
        for j in range(M.shape[1]):
            ax.text(
                j, i, str(M[i, j]),
                ha='center', va='center', fontsize=11
            )

    ax.set_title(title, fontsize=12, pad=14)

    ax.set_xticks(np.arange(3))
    ax.set_xticklabels(x_labels, fontsize=11)

    ax.set_yticks(np.arange(3))
    ax.set_yticklabels(y_labels, fontsize=11)

    ax.set_xlabel("Prediction", labelpad=8)
    ax.set_ylabel("Reference", labelpad=18)   # extra padding → avoids overlap

# adjust layout so nothing overlaps
plt.tight_layout(rect=[0, 0, 1, 0.95], pad=2)

# shared colorbar on the right
cbar = fig.colorbar(im, ax=axes.ravel().tolist(), shrink=0.75, pad=0.02)
cbar.set_label("Count")

plt.show()