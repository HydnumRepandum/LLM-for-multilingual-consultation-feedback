import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns



openai_interest = pd.read_excel('/content/openai_interest.xlsx')
openai_douane = pd.read_excel('/content/openai_douane.xlsx')
openai_imprescriptibility = pd.read_excel('/content/openai_imprescriptibility.xlsx')


gemma_interest = pd.read_excel('/content/0_Moratorium_Interest_Rate.xlsx')
gemma_douane = pd.read_excel('/content/0_Import_Tax_Exemption.xlsx')
gemma_imprescriptibility = pd.read_excel('/content/0_Imprescribility.xlsx')


print("openai_interest head:")
display(openai_interest.head())
print("\nopenai_douane head:")
display(openai_douane.head())
print("\nopenai_imprescriptibility head:")
display(openai_imprescriptibility.head())



print("gemma_interest head:")
display(gemma_interest.head())
print("\gemma_douane head:")
display(gemma_douane.head())
print("\gemma_imprescriptibility head:")
display(gemma_imprescriptibility.head())

"""######################OpenAI###########"""

dfs = {
    'openai_interest': openai_interest,
    'openai_douane': openai_douane,
    'openai_imprescriptibility': openai_imprescriptibility
}

for name, df in dfs.items():

    df.dropna(subset=['summary_fr'], inplace=True)


    df['word_count'] = df['summary_fr'].apply(lambda x: len(str(x).split()))


    print(f"\n{name} head with word_count:")
    display(df.head())

df_combined = pd.concat([openai_interest, openai_douane, openai_imprescriptibility], ignore_index=True)

df_combined['word_count'] = df_combined['summary_fr'].apply(lambda x: len(str(x).split()))

display(df_combined.head())

datasets = [
    ('Interest', openai_interest),
    ('Douane', openai_douane),
    ('Imprescriptibility', openai_imprescriptibility)
]


fig, axes = plt.subplots(1, 3, figsize=(18, 6))

for ax, (name, df) in zip(axes, datasets):
    # Calculate statistics
    mean_val = df['word_count'].mean()
    median_val = df['word_count'].median()

    # Print statistics
    print(f"--- {name} ---")
    print(f"Mean: {mean_val:.2f}")
    print(f"Median: {median_val:.2f}\n")

    # Plot histogram
    sns.histplot(df['word_count'], kde=True, ax=ax, color='skyblue', bins=20)
    ax.axvline(mean_val, color='red', linestyle='--', linewidth=2, label=f'Mean: {mean_val:.2f}')
    ax.axvline(median_val, color='green', linestyle='-', linewidth=2, label=f'Median: {median_val:.2f}')

    ax.set_title(f'Word Count Distribution: {name}')
    ax.set_xlabel('Word Count')
    ax.set_ylabel('Frequency')
    ax.legend()

plt.tight_layout()
plt.show()

mean_Words = df_combined['word_count'].mean()
median_Words = df_combined['word_count'].median()

print(f"Mean Word count: {mean_Words:.2f}")
print(f"Median Word count: {median_Words:.2f}")


plt.figure(figsize=(10, 6))
sns.histplot(df_combined['word_count'], kde=True, color='skyblue', bins=30)
plt.axvline(mean_Words, color='red', linestyle='--', linewidth=2, label=f'Mean: {mean_Words:.2f}')
plt.axvline(median_Words, color='green', linestyle='-', linewidth=2, label=f'Median: {median_Words:.2f}')

plt.title('Distribution of Word Counts (GPT-5-mini)')
plt.xlabel('Word Count')
plt.ylabel('Frequency')
plt.legend()
plt.show()

